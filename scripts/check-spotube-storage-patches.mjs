import assert from 'node:assert/strict';
import {patchEmbeddedDatabase,patchEmbeddedLogger,patchWindowsStorageIdentity} from '../integrations/spotube/storage-patches.mjs';
const imports="import 'dart:io';\nimport 'package:path/path.dart';\nimport 'package:path_provider/path_provider.dart';\n";
const logger=imports+"class LogFixture {\n  static Future<File> getLogsPath() async {\n    final dir = (await getApplicationDocumentsDirectory()).path;\n    return File(join(dir, '.spotube_logs'));\n  }\n}\n";
const patched=patchEmbeddedLogger(logger);
assert(patched.indexOf('getApplicationSupportDirectory()')<patched.indexOf('getApplicationDocumentsDirectory()'));
assert(patched.includes("if (const bool.fromEnvironment('ANF_EMBEDDED', defaultValue: true))"));
assert(patched.includes("File(join(support.path, 'logs', 'spotube.log'))"));
assert(patched.endsWith("    final dir = (await getApplicationDocumentsDirectory()).path;\n    return File(join(dir, '.spotube_logs'));\n  }\n}\n"),'Standalone branch must remain intact');
assert.equal(patchEmbeddedLogger(logger.replaceAll('\n','\r\n')),patched);
assert.throws(()=>patchEmbeddedLogger(patched),/exactly once/);
assert.throws(()=>patchEmbeddedLogger(logger+logger),/exactly once/);
assert.throws(()=>patchEmbeddedLogger(logger.replace("import 'dart:io';",'')),/imports changed/);
assert.equal(patchEmbeddedDatabase("File(join(dbFolder.path, 'db.sqlite'))"),"File(join(dbFolder.path, 'anf-spotube.sqlite'))");
assert.throws(()=>patchEmbeddedDatabase('changed database constructor'),/exactly once/);
const rc='VALUE "CompanyName", "oss.krtirtho" "\\0"\nVALUE "ProductName", "spotube" "\\0"';
assert.equal(patchWindowsStorageIdentity(rc),'VALUE "CompanyName", "AnF" "\\0"\nVALUE "ProductName", "AnFMusic" "\\0"');
assert.throws(()=>patchWindowsStorageIdentity(rc+rc),/exactly once/);
assert.throws(()=>patchWindowsStorageIdentity(rc.replace('ProductName','ChangedName')),/exactly once/);
console.log('PASS: scoped embedded logs, unchanged standalone branch, strict identity/DB drift refusal and CRLF inputs. No file or credential access.');
