import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const require=createRequire(new URL('../windows/package.json',import.meta.url));
const {build}=require('esbuild');
const result=await build({entryPoints:[fileURLToPath(new URL('../windows/src/workspace/skill-pack.ts',import.meta.url))],bundle:true,platform:'node',format:'esm',write:false});
const {skillPack}=await import('data:text/javascript;base64,'+Buffer.from(result.outputFiles[0].text).toString('base64'));
await assert.rejects(()=>skillPack('Test','',[]),/draft/);
await assert.rejects(()=>skillPack('Test','Draft',[]),/readable sources/);
await assert.rejects(()=>skillPack('Test','Draft',[{name:'Empty',text:''}]),/readable sources/);
await assert.rejects(()=>skillPack('Test','Draft',[{name:'Huge',text:'x'.repeat(2_000_001)}]),/export limit/);
const sources=[{name:'Book [one]',text:'Evidence 🌿',pages:[{number:3,ocr:true}]}];
const files=await skillPack('Unsafe:\n../../title','Reviewed draft',sources);
assert.deepEqual(files.map(f=>f.name),['SKILL.md','draft.md','coverage.json','references/source-1.md']);
assert.match(files[0].text,/name: unsafe-title/);assert(!files[0].text.includes('name: ../'));
assert.equal(files[1].text,'Reviewed draft');assert.match(files[3].text,/Evidence 🌿/);
const coverage=JSON.parse(files[2].text).sources[0];
assert.equal(coverage.extractedBytes,new TextEncoder().encode(sources[0].text).length);
assert.equal(coverage.pages[0].ocr,true);assert.equal(coverage.pages[0].number,3);
const changed=await skillPack('Title','Reviewed draft',[{...sources[0],text:'Changed text'}]);
assert.notEqual(JSON.parse(changed[2].text).sources[0].sha256,coverage.sha256);
assert.match(coverage.analysisCoverage,/Not verified/);
console.log('Skill pack checks passed: limits, safe names, exact references, page/OCR metadata and content hashes.');
