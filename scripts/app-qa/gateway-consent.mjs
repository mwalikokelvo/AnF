import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {fileURLToPath,pathToFileURL} from 'node:url';
import path from 'node:path';
import fs from 'node:fs/promises';
import {chromium} from 'playwright-core';
const root=fileURLToPath(new URL('../../',import.meta.url));
const {build}=createRequire(path.join(root,'windows/package.json'))('esbuild');
const out=path.join(root,'windows/target/gateway-consent-check');
await fs.mkdir(out,{recursive:true});
await build({stdin:{contents:`import {confirmGatewayContext} from './src/workspace/gateway-consent';window.requestConsent=(provider,sources,history,memory)=>{window.approved='pending';void confirmGatewayContext(provider,sources,history,memory).then(value=>window.approved=value);};`,resolveDir:path.join(root,'windows'),loader:'ts'},bundle:true,format:'iife',outfile:path.join(out,'consent.js')});
await fs.writeFile(path.join(out,'index.html'),'<meta charset="utf-8"><script src="consent.js"></script>');
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_BIN||undefined,channel:process.env.CHROMIUM_BIN?undefined:'msedge',headless:true});
try {
  const page=await browser.newPage();
  await page.goto(pathToFileURL(path.join(out,'index.html')).href);
  await page.evaluate(()=>window.requestConsent('gateway',[],0,''));
  await page.waitForFunction(()=>window.approved===true);
  assert.equal(await page.locator('dialog').count(),0);
  const request=()=>page.evaluate(()=>window.requestConsent('gateway',[{name:'<img src=x onerror="window.injected=true">',text:'Private source'}],2,'Remembered preferences'));
  await request();
  const dialog=page.getByRole('dialog',{name:'Confirm AI context sharing'});
  await dialog.waitFor();
  assert.equal(await dialog.locator('img').count(),0,'Source names must be text, never markup');
  assert.match(await dialog.innerText(),/2 recent conversation messages/);
  assert.match(await dialog.innerText(),/Saved conversation memory/);
  assert.equal(await page.evaluate(()=>window.approved),'pending');
  await dialog.getByRole('button',{name:'Keep context on this device'}).click();
  await page.waitForFunction(()=>window.approved===false);
  await request();
  await dialog.getByRole('button',{name:'Send this context for this answer'}).click();
  await page.waitForFunction(()=>window.approved===true);
  await request();
  await dialog.waitFor();
  await page.keyboard.press('Escape');
  await page.waitForFunction(()=>window.approved===false);
  await page.evaluate(()=>window.requestConsent('managed',[],1,''));
  await dialog.waitFor();assert.match(await dialog.innerText(),/selected provider may be online/);
  await page.keyboard.press('Escape');await page.waitForFunction(()=>window.approved===false);
  console.log('PASS: real context disclosure dialog, explicit per-answer acceptance, cancel/Escape, history-only managed routing and safe document labels. No provider contacted.');
} finally {await browser.close();}
