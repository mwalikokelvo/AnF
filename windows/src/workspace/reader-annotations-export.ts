/**
 * Reader annotations exporter for AnF Deep Reader.
 * Formats highlighted quotes, user notes, colors, and section offsets
 * into standard Obsidian-compatible Markdown summary notes.
 */

export interface AnnotationItem {
  start: number;
  end: number;
  color: string;
  note?: string;
  id: string;
}

export function formatAnnotationsToMarkdown(
  documentTitle: string,
  documentText: string,
  annotations: AnnotationItem[]
): string {
  if (!annotations || annotations.length === 0) {
    return `# Highlights from ${documentTitle}\n\n*No annotations saved yet.*\n`;
  }

  // Sort annotations in order of appearance in the document
  const sorted = [...annotations].sort((a, b) => a.start - b.start);
  const lines: string[] = [
    `# Highlights from ${documentTitle}`,
    `*Generated by AnF Deep Reader on ${new Date().toLocaleDateString()} · ${sorted.length} highlight${
      sorted.length === 1 ? '' : 's'
    }*\n`,
  ];

  for (let i = 0; i < sorted.length; i++) {
    const ann = sorted[i];
    const excerpt = documentText.slice(ann.start, ann.end).trim();
    lines.push(`### Quote ${i + 1} (${ann.color.toUpperCase()})`);
    lines.push(`> ${excerpt.replace(/\n/g, '\n> ')}\n`);
    if (ann.note && ann.note.trim()) {
      lines.push(`**Note:** ${ann.note.trim()}\n`);
    }
  }

  return lines.join('\n');
}
